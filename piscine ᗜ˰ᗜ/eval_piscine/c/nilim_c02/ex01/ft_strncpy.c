char	*ft_strncpy(char *dest, char *src, unsigned int n)
{
	unsigned int	i;

	i = 0;
	while (i < n && *src != '\0')
	{
		dest[i] = *src;
		i++;
		src++;
	}
	while (i < n)
	{
		dest[i] = '\0';
		i++;
	}
	return (dest);
}

#include <stdio.h>
int main(){
	char *src = "ape";
	char dest[4]= "aaa";
	printf("%s", ft_strncpy(dest, src, 2));
}

